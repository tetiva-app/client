import { build as esbuild } from 'esbuild'
import { writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import ts from 'typescript'

const FRONTEND = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ENTRY = resolve(FRONTEND, 'src/lib/snippets/index.ts')
const DEFAULT_OUTFILE = resolve(FRONTEND, 'src/lib/snippets/dist/snippets.mjs')
const DTS_HEADER = '// Generated by frontend/scripts/build-snippets.mjs from src/lib/snippets/index.ts; do not edit.\n'

export async function build(outfile = DEFAULT_OUTFILE) {
  await esbuild({
    absWorkingDir: FRONTEND,
    entryPoints: [ENTRY],
    outfile,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    minify: false,
    legalComments: 'inline',
    // httpsnippet imports Node's "url"; the trailing slash picks the npm polyfill.
    alias: { url: 'url/' },
    logLevel: 'warning',
  })
  writeFileSync(outfile.replace(/\.mjs$/, '.d.mts'), declarations())
}

function declarations() {
  const config = ts.getParsedCommandLineOfConfigFile(resolve(FRONTEND, 'tsconfig.json'), {}, {
    ...ts.sys,
    onUnRecoverableConfigFileDiagnostic: (d) => { throw new Error(ts.flattenDiagnosticMessageText(d.messageText, '\n')) },
  })
  const options = { ...config.options, noEmit: false, declaration: true, emitDeclarationOnly: true, declarationMap: false, types: [] }
  const host = ts.createCompilerHost(options)
  const emitted = new Map()
  host.writeFile = (fileName, text) => emitted.set(resolve(fileName), text)
  const program = ts.createProgram({ rootNames: [ENTRY], options, host })
  const result = program.emit(undefined, undefined, undefined, true)
  if (result.emitSkipped || result.diagnostics.length) {
    throw new Error(ts.formatDiagnostics(result.diagnostics, host) || 'declaration emit skipped')
  }

  const dtsOf = (file) => file.replace(/\.tsx?$/, '.d.ts')
  const files = new Map()

  const moduleOf = (specifier, fromFile) => {
    const resolved = ts.resolveModuleName(specifier, fromFile, options, host).resolvedModule
    if (!resolved || resolved.isExternalLibraryImport || resolved.extension === ts.Extension.Dts) {
      throw new Error(`${fromFile}: the public declarations cannot import ${specifier}`)
    }
    return dtsOf(resolve(resolved.resolvedFileName))
  }

  const load = (file) => {
    if (files.has(file)) return files.get(file)
    const text = emitted.get(file)
    if (text === undefined) throw new Error(`no declarations emitted for ${file}`)
    const sf = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true)
    const entry = { sf, decls: new Map(), imports: new Map(), exports: new Map() }
    for (const st of sf.statements) {
      if (ts.isImportDeclaration(st)) {
        const bindings = st.importClause?.namedBindings
        if (!bindings || st.importClause.name || !ts.isNamedImports(bindings)) throw new Error(`${file}: unsupported import`)
        const from = moduleOf(st.moduleSpecifier.text, file)
        for (const el of bindings.elements) entry.imports.set(el.name.text, { file: from, name: (el.propertyName ?? el.name).text })
      } else if (ts.isExportDeclaration(st)) {
        if (!st.exportClause || !ts.isNamedExports(st.exportClause)) throw new Error(`${file}: unsupported export`)
        const from = st.moduleSpecifier ? moduleOf(st.moduleSpecifier.text, file) : null
        for (const el of st.exportClause.elements) entry.exports.set(el.name.text, { file: from, name: (el.propertyName ?? el.name).text })
      } else {
        const names = declaredNames(st)
        if (!names) throw new Error(`${file}: unsupported statement ${ts.SyntaxKind[st.kind]}`)
        const exported = !!st.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
        for (const name of names) {
          const d = entry.decls.get(name) ?? { nodes: [], exported: false }
          d.nodes.push(st)
          d.exported ||= exported
          entry.decls.set(name, d)
        }
      }
    }
    files.set(file, entry)
    return entry
  }

  const local = (file, name) => {
    const f = load(file)
    if (f.decls.has(name)) return { file, name }
    const imported = f.imports.get(name)
    return imported ? exported(imported.file, imported.name) : null
  }
  const exported = (file, name) => {
    const f = load(file)
    const re = f.exports.get(name)
    if (re) return re.file ? exported(re.file, re.name) : local(file, re.name)
    if (f.decls.get(name)?.exported) return { file, name }
    throw new Error(`${name} is not exported from ${file}`)
  }

  const order = []
  const owners = new Map()
  const need = (sym) => {
    const key = `${sym.file}#${sym.name}`
    const owner = owners.get(sym.name)
    if (owner === key) return
    if (owner) throw new Error(`two declarations are named ${sym.name}: ${owner} and ${key}`)
    owners.set(sym.name, key)
    order.push(sym)
    for (const node of load(sym.file).decls.get(sym.name).nodes) {
      for (const ref of references(node)) {
        const dep = local(sym.file, ref)
        if (dep) need(dep)
      }
    }
  }

  const index = dtsOf(ENTRY)
  const publicNames = []
  for (const [name, re] of load(index).exports) {
    const sym = re.file ? exported(re.file, re.name) : local(index, re.name)
    need(sym)
    publicNames.push(sym.name === name ? name : `${sym.name} as ${name}`)
  }
  for (const [name, d] of load(index).decls) {
    if (!d.exported) continue
    need({ file: index, name })
    publicNames.push(name)
  }

  const printed = new Set()
  const chunks = []
  for (const sym of order) {
    const { sf, decls } = load(sym.file)
    for (const node of decls.get(sym.name).nodes) {
      if (printed.has(node)) continue
      printed.add(node)
      chunks.push(withoutExport(node, sf))
    }
  }
  return `${DTS_HEADER}${chunks.join('\n')}\nexport { ${publicNames.join(', ')} };\n`
}

function declaredNames(st) {
  if (ts.isInterfaceDeclaration(st) || ts.isTypeAliasDeclaration(st) || ts.isFunctionDeclaration(st)
    || ts.isClassDeclaration(st) || ts.isEnumDeclaration(st)) return st.name ? [st.name.text] : null
  if (ts.isVariableStatement(st)) {
    return st.declarationList.declarations.map((d) => ts.isIdentifier(d.name) ? d.name.text : null).filter(Boolean)
  }
  return null
}

function references(node) {
  const names = []
  const leftmost = (n) => ts.isIdentifier(n) ? n.text : ts.isQualifiedName(n) ? leftmost(n.left)
    : ts.isPropertyAccessExpression(n) ? leftmost(n.expression) : null
  const visit = (n) => {
    if (ts.isImportTypeNode(n)) throw new Error('import() types are not supported in the public declarations')
    if (ts.isTypeReferenceNode(n)) names.push(leftmost(n.typeName))
    else if (ts.isExpressionWithTypeArguments(n)) names.push(leftmost(n.expression))
    else if (ts.isTypeQueryNode(n)) names.push(leftmost(n.exprName))
    ts.forEachChild(n, visit)
  }
  visit(node)
  return names.filter(Boolean)
}

function withoutExport(node, sf) {
  const comments = (ts.getLeadingCommentRanges(sf.text, node.pos) ?? []).map((r) => sf.text.slice(r.pos, r.end))
  const mod = node.modifiers?.find((m) => m.kind === ts.SyntaxKind.ExportKeyword)
  const code = sf.text.slice(mod ? mod.end : node.getStart(sf), node.end).trimStart()
  return [...comments, code].join('\n')
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await build()
}
